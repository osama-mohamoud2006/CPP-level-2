#include<iostream>
using namespace std;
int main() {

	int x = 50;
		int y = 50;

		cout <<"50==50:" << (x == y) << endl;
		cout << "50!=50: " << (x != y) << endl;
		cout << "x>y " << (x > y) << endl;
		cout << "(x<y)" << (x < y) << endl;
		cout << "(x>=y)" << (x >= y) << endl;
		cout << "(x <= y)" << (x <= y) << endl;
}